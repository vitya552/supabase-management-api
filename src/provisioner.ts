const execFileAsync = promisify(execFile)

const COMPOSE_TIMEOUT_MS = 15 * 60 * 1000

export function projectsConfigured(): boolean {
  return Boolean(env.projectsDir && env.projectsHostDir)
}

function projectDir(ref: string): string {
  return path.join(env.projectsDir, ref)
}

function hostDir(ref: string): string {
  return path.posix.join(env.projectsHostDir, ref)
}

function composeProjectName(ref: string): string {
  return `sbproj-${ref}`
}

export function containerName(ref: string, service: string): string {
  return `sbproj-${ref}-${service}`
}

async function compose(ref: string, args: string[]): Promise<void> {
  await execFileAsync(
    'docker',
    [
      'compose',
      '-p',
      composeProjectName(ref),
      '--project-directory',
      projectDir(ref),
      ...args,
    ],
    { timeout: COMPOSE_TIMEOUT_MS, env: process.env }
  )
}

