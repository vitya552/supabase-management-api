function envFile(ref: string, secrets: ProjectSecrets): string {
  const publicBase = `${env.publicUrl.replace(/\/$/, '')}/proj/${ref}`
  return [
    `REF=${ref}`,
    `POSTGRES_PASSWORD=${secrets.postgres_password}`,
    `JWT_SECRET=${secrets.jwt_secret}`,
    `ANON_KEY=${secrets.anon_key}`,
    `SERVICE_ROLE_KEY=${secrets.service_role_key}`,
    `SITE_URL=${env.publicUrl}`,
    `API_EXTERNAL_URL=${publicBase}/auth/v1`,
    `STORAGE_PUBLIC_URL=${publicBase}`,
    `SUPABASE_INTERNAL_URL=http://management-api:8085/proj/${ref}`,
    '',
  ].join('\n')
}

const DB_INIT_FILES = [
  'realtime.sql',
  'webhooks.sql',
  'roles.sql',
  'jwt.sql',
  '_supabase.sql',
  'logs.sql',
  'pooler.sql',
]

async function writeProjectFiles(ref: string, secrets: ProjectSecrets): Promise<void> {
  const dir = projectDir(ref)
  await mkdir(path.join(dir, 'db-init'), { recursive: true })
  await mkdir(path.join(dir, 'db-data'), { recursive: true })
  await mkdir(path.join(dir, 'storage'), { recursive: true })
  await mkdir(path.join(dir, 'functions'), { recursive: true })

  for (const file of DB_INIT_FILES) {
    await copyFile(path.join(env.dbInitDir, file), path.join(dir, 'db-init', file))
  }

  // The edge runtime needs the `main` dispatcher; reuse the stack's one.
  const mainDispatcher = path.join(env.functionsDir, 'main')
  await cp(mainDispatcher, path.join(dir, 'functions', 'main'), { recursive: true })

  await writeFile(path.join(dir, '.env'), envFile(ref, secrets), { mode: 0o600 })
  await writeFile(path.join(dir, 'docker-compose.yml'), composeFile(ref))
}

export function generateProjectSecrets(): ProjectSecrets {
  const jwtSecret = randomBytes(32).toString('base64url')
  return {
    postgres_password: randomBytes(24).toString('hex'),
    jwt_secret: jwtSecret,
    anon_key: mintApiKey('anon', jwtSecret),
    service_role_key: mintApiKey('service_role', jwtSecret),
  }
}

/**
 * Creates the project record and provisions the stack in the background.
 * Returns immediately with the COMING_UP record; poll status afterwards.
 */
export async function provisionProject(input: {
  name: string
  organizationId: number
}): Promise<ProjectRecord> {
  const ref = generateRef()
  const secrets = generateProjectSecrets()
  const record = await createProjectRecord({
    ref,
    name: input.name,
    organizationId: input.organizationId,
    kind: 'compose',
    secrets,
    status: 'COMING_UP',
  })

  void (async () => {
    try {
      await writeProjectFiles(ref, secrets)
      await compose(ref, ['--env-file', path.join(projectDir(ref), '.env'), 'up', '-d'])
      await updateProjectStatus(ref, 'ACTIVE_HEALTHY')
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      console.error(`provisioning ${ref} failed:`, message)
      await updateProjectStatus(ref, 'INIT_FAILED', message.slice(0, 2000)).catch(() => {})
    }
  })()

  return record
}

/** Tears the stack down (containers + data) and removes the record. */
export async function deprovisionProject(ref: string): Promise<void> {
  const project = await getProject(ref)
  if (!project) return
  await updateProjectStatus(ref, 'GOING_DOWN')
  try {
    if (project.kind === 'compose') {
      await compose(ref, ['down', '-v', '--remove-orphans']).catch((err) => {
        console.error(`compose down for ${ref} failed:`, err)
      })
      await rm(projectDir(ref), { recursive: true, force: true })
    }
  } finally {
    await deleteProjectRecord(ref)
  }
}

/** Restarts the stack of an existing compose project (after host reboot etc). */
export async function resumeProjects(): Promise<void> {
  if (!projectsConfigured()) return
  const projects = await listProjects()
  const refs = new Set((await readdir(env.projectsDir).catch(() => [])) as string[])
  for (const project of projects) {
    if (project.kind !== 'compose' || !refs.has(project.ref)) continue
    try {
      await compose(project.ref, [
        '--env-file',
        path.join(projectDir(project.ref), '.env'),
        'up',
        '-d',
      ])
    } catch (err) {
      console.error(`resuming ${project.ref} failed:`, err)
    }
  }
}
